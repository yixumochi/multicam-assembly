def _side(case, event_ids, observation):
    return {"case": case, "event_ids": event_ids, "observation": observation}


def _comparison(**kwargs):
    required = [
        "comparison_id", "question", "title", "why_comparable", "phase_compatible",
        "axes", "sides", "common", "difference", "unknowns", "scope", "design_check",
        "observation", "interpretation", "maps_to", "provenance", "counts",
        "measurement_basis", "source_kind",
    ]
    missing = [key for key in required if key not in kwargs]
    if missing:
        raise RuntimeError(f"Comparison missing {missing}")
    kwargs.setdefault("blocked_rankings", [])
    kwargs.setdefault("retrieval_attribution", "existing_figure_not_a_new_retrieval_run")
    kwargs["status"] = "agent_candidate"
    kwargs["human_confirmed"] = False
    if not kwargs["phase_compatible"]:
        for blocked in ("efficiency", "minimum_space", "success_rate"):
            if blocked not in kwargs["blocked_rankings"]:
                kwargs["blocked_rankings"].append(blocked)
    return kwargs


