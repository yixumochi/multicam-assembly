def material(n):
    src=Image.open(EVIDENCE/f'evidence/frames/task29_{n:06}.jpg').convert('RGB')
    mask=Image.open(D/f'{n}_raw.png').convert('L')
    if n in boxes:
        bb=boxes[n]
        def native(points):
            return [(round(x/2+bb[0]),round(y/2+bb[1])) for x,y in points]
        fence=Image.new('L',src.size)
        ImageDraw.Draw(fence).polygon(native(envelopes[n]),fill=255)
        mask=ImageChops.multiply(mask,fence)
        draw=ImageDraw.Draw(mask)
        for pts in parts[n]:
            draw.polygon(native(pts),fill=255)
        cable={
            437:[(176,423),(144,428),(110,426),(89,423),(65,405),(48,398),(65,410),(81,430),(93,465),(100,499),(118,513)],
            538:[(190,445),(160,454),(126,461),(99,465),(66,466),(39,466),(32,470),(60,493),(89,527),(120,566),(148,584)],
            639:[(188,498),(159,514),(129,526),(90,536),(56,544),(30,551),(27,560),(45,576),(83,601),(115,628),(149,647),(168,651)]
        }[n]
        cord=Image.new('L',src.size)
        ImageDraw.Draw(cord).line(native(cable),fill=255,width=8,joint='curve')
        dark=src.convert('L').point(lambda value:255 if value<76 else 0)
        mask=ImageChops.lighter(mask,ImageChops.multiply(cord,dark))
        wood=Image.open(WORK/'pilot'/f'V04_{n}_pilot_mask.png').convert('L')
        mask=ImageChops.subtract(mask,wood)
    mask.save(D/f'{n}_mask.png')
    return src,mask

